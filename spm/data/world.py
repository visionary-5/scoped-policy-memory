"""Deterministic policy worlds: shared primitives, item templates and dispatch.

A world is fully determined by ``(rule_type, seed)``. All randomness comes from
``random.Random`` instances seeded with strings, and invented names are checked against the
word list shipped in ``spm/assets/words.txt`` (never the system dictionary), so the same world is
generated byte-for-byte on every machine. ``World.hash()`` fingerprints a world; it seeds all
downstream item sampling, so any change to generation logic must bump a version string.

Two world families are supported:
  * CC-Gen-ST(-Lite) policies (``spm.data.ccgen``), the benchmark used for the main results;
  * the synthetic ``mixed`` world (``spm.data.synthetic``), used only by ``analysis/``.

The seed strings (e.g. ``"w1"``) are part of the reproducibility contract and must not change.
"""
from __future__ import annotations

import hashlib
import json
import random
from dataclasses import dataclass, field
from pathlib import Path

GENERATOR_VERSION = "w1"
KMAX = 1024
SPLITS = ("train", "dev", "test")
CCGEN_RULE_TYPES = ("ccgen_t12a3s1", "ccgen_t12a3s2", "ccgen_t5a5s1",
                    "ccgen_t12a3s1_lite", "ccgen_t12a3s2_lite", "ccgen_t5a5s1_lite")
MIXED_RULE_TYPES = ("mixed",)
DEFAULT_RULE_TYPE = "ccgen_t12a3s1_lite"


def max_new_tokens(rule_type: str) -> int:
    """Decoding cap. An output that reaches the cap is counted as truncated (and wrong)."""
    if rule_type in MIXED_RULE_TYPES:
        return 64
    return 96 if rule_type in CCGEN_RULE_TYPES else 48


# ---------- invented names ----------
_CONS = "bdfgklmnprstvz"
_VOW = "aeiou"
_CODA = ["", "n", "r", "l", "k", "x"]
VERBS = ["ticket", "refund", "rebook", "upgrade", "seat", "bag", "notify", "cancel",
         "lookup", "credit", "transfer", "hold", "meal", "lounge", "voucher", "claim"]
NAME_SPACE = (len(_CONS) * len(_VOW)) ** 2 * len(_CODA)
_DICT_CACHE: set[str] | None = None


def _load_dict() -> set[str]:
    """Fixed English word list (public-domain Webster 2nd) shipped with the package."""
    global _DICT_CACHE
    if _DICT_CACHE is None:
        p = Path(__file__).resolve().parents[1] / "assets" / "words.txt"
        _DICT_CACHE = {w.strip().lower() for w in p.read_text().splitlines()}
    return set(_DICT_CACHE)


class NamePool:
    """Unique invented words that are not English words."""

    def __init__(self, rng: random.Random, words: set[str]):
        self.rng, self.words, self.used = rng, words, set()

    def _word(self, n_syl: int) -> str:
        s = "".join(self.rng.choice(_CONS) + self.rng.choice(_VOW) for _ in range(n_syl))
        return s + self.rng.choice(_CODA)

    def new(self, n_syl: int | None = None) -> str:
        for _ in range(10000):
            w = self._word(n_syl or self.rng.choice((2, 2, 3)))
            if w not in self.words and w not in self.used and len(w) >= 4:
                self.used.add(w)
                return w
        raise RuntimeError("name pool exhausted")

    def similar(self, w: str) -> str:
        """Look-alike decoy: change one vowel or consonant."""
        for _ in range(1000):
            i = self.rng.randrange(len(w))
            pool = _VOW if w[i] in _VOW else _CONS if w[i] in _CONS else None
            if not pool:
                continue
            c = w[:i] + self.rng.choice(pool.replace(w[i], "")) + w[i + 1:]
            if c not in self.words and c not in self.used:
                self.used.add(c)
                return c
        raise RuntimeError("no look-alike decoy found")


# ---------- value splits: train / dev / test ranges are disjoint ----------
def user_id(rng, split):
    lo, hi = {"train": (1000, 5999), "dev": (6000, 6999), "test": (7000, 9999)}[split]
    return f"U{rng.randint(lo, hi)}"


def small_int(rng, split, lo=1, hi=99):
    """Integers in [lo, hi] split by value mod 5: {0,1,2} train, {3} dev, {4} test."""
    want = {"train": (0, 1, 2), "dev": (3,), "test": (4,)}[split]
    while True:
        v = rng.randint(lo, hi)
        if v % 5 in want:
            return v


# ---------- request templates: 20 per family, split 12/3/5 ----------
def _split_templates(ts: list[str]) -> dict[str, list[str]]:
    assert len(ts) == 20, len(ts)
    return {"train": ts[:12], "dev": ts[12:15], "test": ts[15:]}


OPENERS = ["", "Hi. ", "Task: ", "Agent task: ", "New request: "]


def _mk(_openers, bodies):
    return [o + b for o in OPENERS for b in bodies]


def fix_case(req: str) -> str:
    """Capitalise the first letter after the opener."""
    for o in sorted(OPENERS, key=len, reverse=True):
        if req.startswith(o):
            body = req[len(o):]
            return o + body[:1].upper() + body[1:]
    return req


T_MAP = _split_templates(_mk(
    ["", "Please ", "Hi, ", "Could you ", "Agent task: "],
    ["{verb_text} for {user} on {date} using {old}.",
     "use {old} to {verb_text_inf} for {user}, date {date}.",
     "{user} needs this done on {date}: call {old}.",
     "run {old} for customer {user} ({date})."]))
T_NEUTRAL = _split_templates(_mk(
    ["", "Please ", "Hi, ", "Could you ", "Agent task: "],
    ["call {tool} for {user} with code {code}.",
     "{user} needs {tool}, code {code}.",
     "run {tool} (user {user}, code {code}).",
     "use {tool} for {user}; the code is {code}."]))
T_RECALL = ["Question about the rules: {q}\nOptions:\n{opts}\nAnswer with the letter only."]
VERB_TEXT = {v: (f"handle the {v}", f"handle the {v}") for v in VERBS}


@dataclass
class World:
    rule_type: str
    seed: int
    rules: list[dict]
    extra: dict = field(default_factory=dict)

    def subset(self, K: int) -> list[dict]:
        if self.rule_type in MIXED_RULE_TYPES:
            from . import synthetic
            return synthetic.subset(self, K)
        if self.rule_type in CCGEN_RULE_TYPES:
            from . import ccgen
            return ccgen.subset(self, K)
        raise ValueError(f"unknown rule type: {self.rule_type}")

    def hash(self) -> str:
        blob = json.dumps({"v": GENERATOR_VERSION, "t": self.rule_type, "s": self.seed,
                           "r": self.rules, "x": self.extra}, sort_keys=True)
        return hashlib.sha256(blob.encode()).hexdigest()[:12]


def build_world(rule_type: str, seed: int, kmax: int = KMAX) -> World:
    if rule_type in MIXED_RULE_TYPES:
        from . import synthetic
        return synthetic.build(seed, kmax)
    if rule_type in CCGEN_RULE_TYPES:
        from . import ccgen
        return ccgen.build(rule_type, seed)
    raise ValueError(f"unknown rule type: {rule_type}")


# ---------- items ----------
def _call(name: str, **kw) -> list:
    return [name, kw]


def _date(rng, split):
    m = rng.randint(1, 12); d = small_int(rng, split, 1, 28)
    return f"{m:02d}-{d:02d}"


def make_item(world: World, rule: dict, split: str, kind: str, rng: random.Random, K: int) -> dict:
    """kind in exec / decoy / recall (mixed world also: cross). Answers come from the generator."""
    if world.rule_type in MIXED_RULE_TYPES:
        from . import synthetic
        return synthetic.make_item(world, rule, split, kind, rng, K)
    if world.rule_type in CCGEN_RULE_TYPES:
        from . import ccgen
        return ccgen.make_item(world, rule, split, kind, rng, K)
    raise ValueError(f"unknown rule type: {world.rule_type}")


def _recall_item(world, rule, rng, K, item):
    """Multiple-choice recall for a renaming ('map') rule."""
    sub = world.subset(K)
    same = [r for r in sub if r["kind"] == rule["kind"] and r["id"] != rule["id"]]
    if rule["kind"] != "map":
        raise ValueError(f"recall not supported for rule kind {rule['kind']}")
    q = f"What is the current name of the tool `{rule['old']}`?"
    right = f"`{rule['new']}`"
    wrong = [f"`{r['new']}`" for r in rng.sample(same, min(3, len(same)))]
    while len(wrong) < 3:
        wrong.append(f"`{rule['decoy']}`" if f"`{rule['decoy']}`" not in wrong else f"`{rule['old']}`")
    opts = wrong[:3] + [right]; rng.shuffle(opts)
    letter = "ABCD"[opts.index(right)]
    item["tools"] = []
    item["request"] = T_RECALL[0].format(q=q, opts="\n".join(f"{L}) {o}" for L, o in zip("ABCD", opts)))
    item["answer"] = letter
    item["fields"] = {"recall_of": rule["id"]}
    return item


def neutral_item(world: World, split: str, rng: random.Random) -> dict:
    """A tool no rule touches; all arguments are stated in the request (tests retained ability)."""
    tmpl = T_NEUTRAL[split][rng.randrange(len(T_NEUTRAL[split]))]
    tool, user, code = rng.choice(world.extra["neutral_tools"]), user_id(rng, split), small_int(rng, split, 100, 999)
    return {"world": f"{world.rule_type}-s{world.seed}", "rule_type": world.rule_type, "split": split,
            "kind": "neutral", "rule_ids": [], "tools": [f"{tool}(user, code)"],
            "request": fix_case(tmpl.format(tool=tool, user=user, code=code)), "user": user,
            "fields": {"tool": tool, "user": user, "code": code}, "answer": [_call(tool, user=user, code=code)]}


def sample_items(world: World, K: int, split: str, kind: str, n: int, seed: int = 0) -> list[dict]:
    """n items cycling over rules (per-rule counts differ by at most one)."""
    rng = random.Random(f"{world.hash()}-{K}-{split}-{kind}-{seed}")
    if kind == "neutral":
        items = [neutral_item(world, split, rng) for _ in range(n)]
        if world.rule_type in MIXED_RULE_TYPES:  # always-on rules also apply to neutral tools
            from .synthetic import always_args
            for it in items:
                it["answer"][0][1].update(always_args(world.subset(K)))
        return items
    if world.rule_type in MIXED_RULE_TYPES:
        from . import synthetic
        return synthetic.sample_items(world, K, split, kind, n, seed)
    if world.rule_type in CCGEN_RULE_TYPES:
        from . import ccgen
        return ccgen.sample_items(world, K, split, kind, n, seed)
    raise ValueError(f"unknown rule type: {world.rule_type}")


def lookup_solve(world: World, K: int, item: dict):
    """Program oracle: recomputes the gold answer from the rule table and ``item['fields']`` only."""
    f = item["fields"]
    if item["kind"] == "recall":
        return None
    if item["kind"] == "neutral":
        extra = {}
        if world.rule_type in MIXED_RULE_TYPES:
            from .synthetic import always_args
            extra = always_args(world.subset(K))
        return [_call(f["tool"], user=f["user"], code=f["code"], **extra)]
    if world.rule_type in MIXED_RULE_TYPES:
        from . import synthetic
        return synthetic.lookup_solve(world, K, item)
    if world.rule_type in CCGEN_RULE_TYPES:
        from . import ccgen
        return ccgen.lookup_solve(world, K, item)
    raise ValueError(f"unknown rule type: {world.rule_type}")


